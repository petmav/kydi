#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md from the production dependency tree in package-lock.json (dev dependencies
// excluded) plus the bundled DejaVu fonts. Licence texts are read from each installed package and de-duplicated.
//
//   node scripts/third-party-notices.mjs        (run after `npm ci`)
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const lock = JSON.parse(readFileSync(path.join(root, "package-lock.json"), "utf8"));
const own = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));

/** Packages that are installed as optional platform binaries of Next.js but removed from the container image. */
const NOT_SHIPPED = (name) => name === "sharp" || name.startsWith("@img/");

const LICENSE_FILES = /^(licen[sc]e|copying|notice)(\.(md|txt|markdown))?$/i;
const pkgs = [];
for (const [key, meta] of Object.entries(lock.packages)) {
  if (!key || meta.dev || meta.devOptional || meta.link) continue;
  const name = key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
  const dir = path.join(root, key);
  let license = meta.license ?? null;
  let repo = "";
  let text = null;
  if (existsSync(path.join(dir, "package.json"))) {
    const pj = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
    license ??= typeof pj.license === "string" ? pj.license : pj.license?.type ?? null;
    repo = typeof pj.repository === "string" ? pj.repository : pj.repository?.url ?? pj.homepage ?? "";
    const file = readdirSync(dir).find((f) => LICENSE_FILES.test(f));
    if (file) text = readFileSync(path.join(dir, file), "utf8").replace(/\r\n/g, "\n").trim();
  }
  if (!license && text && /^(the )?mit license/i.test(text)) license = "MIT (per LICENSE file)";
  pkgs.push({ name, version: meta.version, license: license ?? "UNKNOWN", repo: repo.replace(/^git\+/, "").replace(/\.git$/, ""), text, shipped: !NOT_SHIPPED(name) });
}
pkgs.sort((a, b) => a.name.localeCompare(b.name) || String(a.version).localeCompare(String(b.version)));

const shipped = pkgs.filter((p) => p.shipped);
const counts = {};
for (const p of shipped) counts[p.license] = (counts[p.license] ?? 0) + 1;

const texts = new Map();
for (const p of shipped) {
  if (!p.text) continue;
  const h = createHash("sha256").update(p.text).digest("hex");
  if (!texts.has(h)) texts.set(h, { text: p.text, users: [] });
  texts.get(h).users.push(`${p.name}@${p.version}`);
}

const font = readFileSync(path.join(root, "assets", "fonts", "DejaVu-LICENSE.txt"), "utf8").replace(/\r\n/g, "\n").trim();
const lines = [];
lines.push("# Third-party notices", "");
lines.push(`Kydi ${own.version} is MIT licensed (see LICENSE). It ships the third-party components listed below. This file is`);
lines.push("generated by `node scripts/third-party-notices.mjs` from the production dependency tree in `package-lock.json`;");
lines.push("development-only dependencies (build, lint and test tools) are not part of the application or its container image.", "");
lines.push("## Bundled fonts", "");
lines.push("PDFs embed DejaVu Sans (`assets/fonts/DejaVuSans*.ttf`), DejaVu fonts by the DejaVu project, derived from the");
lines.push("Bitstream Vera fonts (Bitstream Vera licence, with Arev additions under the same terms). Full licence:", "");
lines.push("```text", font, "```", "");
lines.push("## Container base images", "");
lines.push("- `node` (Node.js, MIT and bundled third-party licences; Alpine Linux packages under their own licences).");
lines.push("- `postgres` (PostgreSQL Licence) for the database service.", "");
lines.push("## Production npm dependencies", "");
lines.push(`${shipped.length} packages. Licences: ${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ")}.`, "");
lines.push("| Package | Version | Licence | Source |", "| --- | --- | --- | --- |");
for (const p of shipped) lines.push(`| ${p.name} | ${p.version} | ${p.license} | ${p.repo || ""} |`);
lines.push("");
const notShipped = pkgs.filter((p) => !p.shipped);
if (notShipped.length) {
  lines.push("Not shipped: Next.js lists the optional image optimiser `sharp` and its prebuilt `@img/*` binaries (libvips,");
  lines.push("LGPL-3.0-or-later) as optional dependencies. Kydi does not use `next/image` (`images.unoptimized`), and the");
  lines.push("Dockerfile removes them from the runtime image.", "");
}
lines.push("## Licence texts", "");
lines.push("Texts as included by each package (identical texts are listed once).", "");
for (const { text, users } of texts.values()) {
  lines.push(`### ${users.length > 6 ? `${users.slice(0, 6).join(", ")} and ${users.length - 6} more` : users.join(", ")}`, "");
  if (users.length > 6) lines.push(`Applies to: ${users.join(", ")}.`, "");
  lines.push("```text", text.replace(/```/g, "'''"), "```", "");
}
const missing = shipped.filter((p) => !p.text);
if (missing.length) {
  lines.push("### Packages without a licence file", "");
  lines.push("These packages declare their licence in package.json only; the standard text of that licence applies.", "");
  for (const p of missing) lines.push(`- ${p.name}@${p.version}: ${p.license}`);
  lines.push("");
}
writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), lines.join("\n"));
console.log(`THIRD_PARTY_NOTICES.md: ${shipped.length} packages, ${texts.size} distinct licence texts, ${missing.length} without a licence file`);
