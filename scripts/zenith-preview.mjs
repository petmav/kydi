#!/usr/bin/env node
// Preview helper: the repository root holds the PUBLISH manifest (zenith-compose.yml), but `zenith check` and
// `zenith up` apply the stricter preview policy, which forbids x-zenith.env / x-zenith.storage. This script
// temporarily copies zenith-compose.preview.yml over zenith-compose.yml, runs `zenith check --upload-size`,
// optionally `zenith up` (only with --up), and ALWAYS restores the publish manifest byte for byte (finally
// block, SIGINT/SIGTERM handlers, and a backup file whose path is printed in case the process is killed).
//
//   npm run zenith:preview              # check only (no network upload)
//   npm run zenith:preview -- --up      # check, then start a 20-minute preview (needs `zenith auth login`)
//
// With --up, SESSION_SECRET and APP_ENCRYPTION_KEY are appended to the gitignored .env.local when missing
// (random values; `zenith up` sends .env.local to the preview as secrets).
import { spawnSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import { copyFileSync, existsSync, readFileSync, appendFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const manifest = path.join(root, "zenith-compose.yml");
const preview = path.join(root, "zenith-compose.preview.yml");
const backup = path.join(tmpdir(), `kydi-zenith-compose.publish.${process.pid}.yml`);
const args = process.argv.slice(2);
const wantUp = args.includes("--up");

const sha = (buf) => createHash("sha256").update(buf).digest("hex");
const original = readFileSync(manifest);
const originalHash = sha(original);
let restored = false;

function restore() {
  if (restored) return;
  writeFileSync(manifest, original);
  const now = sha(readFileSync(manifest));
  if (now !== originalHash) {
    console.error(`[zenith-preview] ERROR: restored manifest hash ${now} differs from ${originalHash}. Backup: ${backup}`);
    process.exitCode = 2;
    return;
  }
  restored = true;
  rmSync(backup, { force: true });
  console.log(`[zenith-preview] publish manifest restored (sha256 ${originalHash})`);
}

for (const signal of ["SIGINT", "SIGTERM", "SIGHUP"]) {
  process.on(signal, () => {
    restore();
    process.exit(130);
  });
}

function run(cmd, cmdArgs) {
  console.log(`[zenith-preview] $ ${cmd} ${cmdArgs.join(" ")}`);
  const r = spawnSync(cmd, cmdArgs, { cwd: root, stdio: "inherit", shell: process.platform === "win32", env: { ...process.env, NO_COLOR: "1" } });
  if (r.error) throw r.error;
  return r.status ?? 1;
}

function ensurePreviewSecrets() {
  const envLocal = path.join(root, ".env.local");
  const current = existsSync(envLocal) ? readFileSync(envLocal, "utf8") : "";
  const missing = ["SESSION_SECRET", "APP_ENCRYPTION_KEY"].filter((k) => !new RegExp(`^\\s*${k}\\s*=`, "m").test(current));
  if (!missing.length) return;
  const lines = missing.map((k) => `${k}="${randomBytes(32).toString("hex")}"`);
  appendFileSync(envLocal, `${current && !current.endsWith("\n") ? "\n" : ""}# Generated by scripts/zenith-preview.mjs for previews\n${lines.join("\n")}\n`);
  console.log(`[zenith-preview] added ${missing.join(", ")} to .env.local (gitignored)`);
}

let status = 1;
try {
  if (!existsSync(preview)) throw new Error("zenith-compose.preview.yml is missing");
  copyFileSync(manifest, backup);
  console.log(`[zenith-preview] backup of the publish manifest: ${backup}`);
  copyFileSync(preview, manifest);
  status = run("zenith", ["check", "--upload-size"]);
  if (status !== 0) {
    console.error("[zenith-preview] zenith check failed on the preview manifest");
  } else if (wantUp) {
    ensurePreviewSecrets();
    const upArgs = args.filter((a) => a !== "--up");
    status = run("zenith", ["up", ...upArgs]);
  } else {
    console.log("[zenith-preview] zenith check passed (not starting a preview; pass --up to run `zenith up`)");
  }
} catch (e) {
  console.error(`[zenith-preview] ${e instanceof Error ? e.message : e}`);
  status = 1;
} finally {
  restore();
}
process.exit(process.exitCode && process.exitCode !== 0 ? process.exitCode : status);
