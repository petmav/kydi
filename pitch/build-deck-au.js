// Builds the Australian pitch deck. Run from the repo root:
//   NODE_PATH=<dir with pptxgenjs> PPTX_SKILL=<pptx skill dir> DECK_OUT=Kydi-pitch-AU.pptx node pitch/build-deck-au.js
const path = require("path");
const fs = require("fs");
const pptxgen = require("pptxgenjs");
const { applyTheme } = require(process.env.PPTX_SKILL + "/scripts/apply_theme.js");

const here = (f) => path.join(__dirname, f);
