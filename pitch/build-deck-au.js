    dk1: "0E1A33", // ink
    lt1: "FFFFFF",
    dk2: "5B6782", // muted text
    lt2: "F4F7FC", // page
    accent1: "026BEF", // brand blue (the mark and the dot over the i)
    accent2: "0B1630", // navy, dark slides
    accent3: "8DB8FF", // sky, secondary series and text on navy
    accent4: "E3E9F3", // hairlines
