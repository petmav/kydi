// ---------- helpers ----------
const shadow = () => ({ type: "outer", color: "0B1630", opacity: 0.08, blur: 18, offset: 4, angle: 90 });
const T = (s, text, o) => s.addText(text, { margin: 0, isTextBox: true, valign: "top", ...o });

const eyebrow = (s, text) => {
  s.addShape(pres.shapes.OVAL, { x: ML, y: 0.47, w: 0.13, h: 0.13, fill: { color: C.accent1 }, line: { type: "none" }, objectName: "Eyebrow dot" });
  T(s, text.toUpperCase(), { x: ML + 0.24, y: 0.38, w: 8, h: 0.3, fontSize: 12, bold: true, color: C.accent1, charSpacing: 1.5, valign: "middle", objectName: "Eyebrow" });
};
const card = (s, x, y, w, h, name, fill = C.background1) =>
  s.addShape(pres.shapes.ROUNDED_RECTANGLE, { x, y, w, h, rectRadius: 0.12, fill: { color: fill }, line: { color: HEX.accent4, width: 0.75 }, shadow: shadow(), objectName: name });
const source = (s, text) => T(s, text, { x: ML, y: 6.42, w: CW, h: 0.42, fontSize: 10, color: C.text2, valign: "bottom", objectName: "Sources" });
const rings = (s, cx, cy, radii) =>
  radii.forEach((r, i) => s.addShape(pres.shapes.OVAL, { x: cx - r, y: cy - r, w: 2 * r, h: 2 * r, fill: { type: "none" }, line: { color: HEX.accent6, width: 1.25 }, objectName: `Ring ${i + 1}` }));
const numberDot = (s, x, y, n, d = 0.36, name = `Marker ${n}`) =>
  s.addText(String(n), { shape: pres.shapes.OVAL, x, y, w: d, h: d, fill: { color: C.accent1 }, line: { color: HEX.lt1, width: 1.5 }, color: C.background1, fontSize: 13, bold: true, align: "center", valign: "middle", margin: 0, objectName: name });
const chartText = { titleFontFace: "+mn-lt", dataLabelFontFace: "+mn-lt", catAxisLabelFontFace: "+mn-lt", valAxisLabelFontFace: "+mn-lt", legendFontFace: "+mn-lt" };

